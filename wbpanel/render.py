# -*- coding: utf-8 -*-
"""
Подстановка CSS-переменных для старых браузеров и librsvg.
"""

import re
from .const import log


# ==========================================================================
#  HTTP
# ==========================================================================

# --------------------------------------------------------------------------
#  Совместимость со старыми браузерами
# --------------------------------------------------------------------------
# Android 5.1 несёт WebView на движке Chrome 39-40. В нём нет двух вещей,
# на которых построен шаблон:
#   * CSS-переменных (var) - появились в Chrome 49. Без них не резолвятся
#     ВСЕ цвета и размеры шрифта, и половина картинки не рисуется;
#   * fetch() - появился в Chrome 42, на нём держится страница.
# Поэтому для таких браузеров отдаём SVG с уже подставленными значениями
# и страницу на XMLHttpRequest.
#
# Заодно это готовое решение для ESP32-дисплея: librsvg тоже не понимает var().

#: Шаблоны компилируются один раз: каждый из них ходит по документу в
#: полтораста килобайт, и разбор шаблона на каждый ответ там лишний.
_VAR_RE = re.compile(r"var\((--[\w-]+)\)")
#: Шаблоны уборки начинаются с литерала. Это не косметика: с ведущим
#: [ \t]* и с просмотром назад движок не может искать подстроку и идёт
#: по документу посимвольно. На панели в полтораста килобайт разница
#: десятикратная - 3.7 мс против 0.85 и 2.8 против 0.25.
#: Ведущие пробелы при этом остаются в разметке; на отображение они не
#: влияют, а стоят копейки места.
_CALC_RE = re.compile(r"calc\(\s*([\d.]+)px\s*\*\s*([\d.]+)\s*\)")
_DECL_RE = re.compile(r"--[\w-]+[ \t]*:[^;\n]*;")
_FS_ATTR_RE = re.compile(r'style="--fs:[\d.]+"[ \t]*')


def _css_vars(style, selector):
    """Объявления --name: value из блока с заданным селектором."""
    match = re.search(re.escape(selector) + r"\s*\{([^}]*)\}", style)
    if not match:
        return {}
    return dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", match.group(1)))


def resolve_css_vars(svg, theme="light", fs=1.0):
    """
    Подставить значения CSS-переменных прямо в разметку.

    Делается ВСЕГДА, для любого браузера.

    Где переменная не поддерживается, свойство просто игнорируется, и fill
    становится чёрным по умолчанию: плитки есть, нажатия работают, а на
    тёмном фоне не видно ничего. Именно так вело себя старое устройство.

    Современным браузерам подстановка не мешает - результат тот же самый.
    Заодно решается задача для rsvg-convert и ESP32-дисплея: librsvg
    переменные тоже не понимает.

    Отключить, если когда-нибудь понадобится сырой вариант: ?flat=0
    """
    style_match = re.search(r"<style>(.*?)</style>", svg, re.S)
    if not style_match:
        return svg
    style = style_match.group(1)

    # Угловые скобки внутри style ломают разбор XML: строгий парсер видит
    # в них тег и до закрывающего style доходит с несведённым балансом.
    # Встроенная в разметку панель при этом работает - HTML-парсер
    # снисходителен, - а вот как картинка (сводная страница показывает
    # панели через img) она уже не открывается. Старые движки и вовсе
    # обрывают таблицу стилей на этом месте, теряя всё, что ниже.
    # Стоили эти грабли двух вечеров, поэтому теперь они слышны.
    for bracket in "<>":
        if bracket in style:
            line = next((l.strip() for l in style.split("\n") if bracket in l), "")
            log.warning("угловая скобка внутри <style> сломает разбор XML: %s",
                        line[:100])
            break

    values = _css_vars(style, "svg")
    if theme == "dark":
        values.update(_css_vars(style, ".dark"))
    values["--fs"] = str(fs)

    def replace(match):
        return values.get(match.group(1), "inherit")

    # Переменная может ссылаться на переменную. Разворачиваем такие
    # ссылки в самом словаре - он маленький, - а по документу проходим
    # ровно один раз. Раньше проход был рекурсивным: полтораста
    # килобайт сканировались два-три раза подряд, и это стоило около
    # четверти времени всего ответа.
    values = dict((k, v.strip()) for k, v in values.items())
    for _ in range(4):
        nested = [k for k, v in values.items() if "var(" in v]
        if not nested:
            break
        for key in nested:
            values[key] = _VAR_RE.sub(replace, values[key])

    body = _VAR_RE.sub(replace, svg)

    # calc(9.5px * 2.17) -> 20.6px: старые движки такое умеют, но пусть
    # не считают лишнего, а заодно уйдут выражения с потерявшимися var.
    # Сворачивается после подстановки: до неё множитель ещё var(--fs).
    def calc(m):
        try:
            return "%.2fpx" % (float(m.group(1)) * float(m.group(2)))
        except ValueError:
            return m.group(0)
    body = _CALC_RE.sub(calc, body)

    # Сами объявления и служебный атрибут больше не нужны. Шаблон
    # привязан к литералу style="--fs: - внутрь тега <style> он попасть
    # не может, там за именем тега идёт закрывающая скобка.
    body = _DECL_RE.sub("", body)
    return _FS_ATTR_RE.sub("", body)
